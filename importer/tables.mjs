// League tables from BBC Sport table pages -> public.pro_tables (one row per competition, replaced each run).
//   node importer/tables.mjs [--sql importer/out/tables.sql] [--force]
// Same polling rule as the match import: only 13:00 to 05:59 UK time unless --force.
import fs from 'node:fs';
import path from 'node:path';
import { htmlToLines } from './sources/bbc.mjs';
import { inPollWindow, ukHour } from './import.mjs';

export const COMPS = [
  ['premier-league', 'Premier League', 'premier-league'],
  ['championship', 'Championship', 'championship'],
  ['league-one', 'League One', 'league-one'],
  ['league-two', 'League Two', 'league-two'],
  ['scottish-premiership', 'Scottish Premiership', 'scottish-premiership'],
  ['scottish-championship', 'Scottish Championship', 'scottish-championship'],
  ['scottish-league-one', 'Scottish League One', 'scottish-league-one'],
  ['scottish-league-two', 'Scottish League Two', 'scottish-league-two'],
  ['champions-league', 'Champions League', 'champions-league'],
  ['europa-league', 'Europa League', 'europa-league'],
  ['conference-league', 'Conference League', 'europa-conference-league'],
];

const num = (s) => (/^[-−+]?\d+$/.test(s) ? parseInt(s.replace('−', '-'), 10) : null);

// The page text is: header block, then per team: position, name, 8 numbers (P W D L F A GD Pts), then form tokens (W/D/L + "Result ...").
export function parseTable(lines) {
  const start = lines.findIndex((l) => /^Form, Last \d+ games/i.test(l));
  if (start < 0) return [];
  const rows = [];
  let i = start + 1;
  while (i < lines.length) {
    const pos = num(lines[i]);
    const name = lines[i + 1];
    if (pos == null || !name || num(name) != null) break;
    const n = [];
    for (let k = 0; k < 8; k++) n.push(num(lines[i + 2 + k] ?? ''));
    if (n.some((v) => v == null)) break;
    i += 10;
    const form = [];
    while (i < lines.length && (/^(W|D|L)$/.test(lines[i]) || /^(Result |No Result)/.test(lines[i]))) {
      if (/^(W|D|L)$/.test(lines[i])) form.push(lines[i]);
      i++;
    }
    rows.push({ pos, team: name, p: n[0], w: n[1], d: n[2], l: n[3], gf: n[4], ga: n[5], gd: n[6], pts: n[7], form: form.slice(-6) });
  }
  return rows;
}

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
export function tablesSql(tables) {
  const out = ['-- Generated by importer/tables.mjs. Replaces one row per competition.', 'begin;'];
  for (const t of tables) {
    out.push(`insert into public.pro_tables (comp, name, rows, fetched_at) values (${q(t.comp)}, ${q(t.name)}, ${q(JSON.stringify(t.rows))}::jsonb, now()) on conflict (comp) do update set name = excluded.name, rows = excluded.rows, fetched_at = now();`);
  }
  out.push('commit;');
  return out.join('\n') + '\n';
}

async function main() {
  const args = process.argv.slice(2);
  const force = args.includes('--force');
  const sqlOut = args.includes('--sql') ? args[args.indexOf('--sql') + 1] : null;
  if (!force && !inPollWindow()) { console.log(`Outside the polling window (it is ${ukHour()}:xx UK). Tables not fetched.`); return; }
  const tables = [];
  for (const [comp, name, slug] of COMPS) {
    try {
      const r = await fetch(`https://www.bbc.co.uk/sport/football/${slug}/table`, { headers: { 'User-Agent': 'Mozilla/5.0 (compatible; myteamcompanion/0.1)' } });
      if (!r.ok) { console.log(`${comp}: HTTP ${r.status}, skipped`); continue; }
      const rows = parseTable(htmlToLines(await r.text()));
      if (rows.length < 4) { console.log(`${comp}: no table found, skipped`); continue; }
      console.log(`${comp}: ${rows.length} teams, leader ${rows[0].team} ${rows[0].pts} pts`);
      tables.push({ comp, name, rows });
    } catch (e) { console.log(`${comp}: ${e.message}, skipped`); }
    await new Promise((res) => setTimeout(res, 1200));
  }
  if (sqlOut && tables.length) { fs.mkdirSync(path.dirname(sqlOut), { recursive: true }); fs.writeFileSync(sqlOut, tablesSql(tables)); console.log(`wrote ${sqlOut} (${tables.length} tables)`); }
}
if (import.meta.url === `file://${process.argv[1]}`) main().catch((e) => { console.error(e.message); process.exit(1); });
